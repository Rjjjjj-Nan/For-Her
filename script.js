document.querySelectorAll(".photo-card").forEach((card) => {
  card.addEventListener("click", () => {
    card.classList.toggle("is-flipped");
    card.setAttribute("aria-pressed", card.classList.contains("is-flipped"));
  });
});

unlockForm.addEventListener("submit", (event) => {
  event.preventDefault();
  errorMessage.textContent = "";

  if (anniversaryInput.value !== surprise.anniversary) {
    errorMessage.textContent = "That date isn't quite right — try again, babyyy ko.";
    anniversaryInput.focus();
    return;
  }

  unlockScreen.classList.add("is-hidden");
  letterScreen.classList.remove("is-hidden");
  letterScreen.classList.add("is-revealing");
  letterScreen.scrollIntoView({ behavior: "smooth", block: "start" });
});

replayButton.addEventListener("click", () => {
  letterScreen.classList.remove("is-revealing");
  void letterScreen.offsetWidth;
  letterScreen.classList.add("is-revealing");
  window.scrollTo({ top: 0, behavior: "smooth" });
});
